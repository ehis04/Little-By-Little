#!/usr/bin/env bash
# CI check: validates a PR title and body against the same rules as the commit-msg hook.
# Usage: scripts/check-pr-text.sh "<title>" "<body>"
#    or: PR_TITLE=... PR_BODY=... scripts/check-pr-text.sh
set -euo pipefail

title="${1:-${PR_TITLE:-}}"
body="${2:-${PR_BODY:-}}"

title_pattern='^(feat|fix|chore|refactor|perf|test|docs|ci|build|style|revert)(\([a-z0-9-]+\))?!?: [a-z0-9].{0,70}$'
# Keep in sync with .githooks/commit-msg (scripts/test-git-hygiene.sh checks this).
forbidden='co-authored-by|generated with|generated by|created with|claude|anthropic|chatgpt|openai|copilot|gemini|ai-generated|ai generated|ai-assisted|ai assisted|llm-generated|claude\.ai|noreply@anthropic|claude-session'

status=0

if ! [[ "$title" =~ $title_pattern ]]; then
  echo "✖ PR title must be a conventional commit summary, e.g. feat(plan): show best time on plan detail"
  echo "  Got: $title"
  status=1
fi
if [[ "$title" =~ \.$ ]]; then
  echo "✖ PR title must not end with a full stop."
  status=1
fi

for part in title body; do
  text="${!part}"
  if printf '%s\n' "$text" | grep -qiE "$forbidden"; then
    echo "✖ PR $part must not contain AI attribution, co-author trailers, session links or tool references."
    echo "  Matched line(s):"
    printf '%s\n' "$text" | grep -inE "$forbidden" | sed 's/^/    /'
    status=1
  fi
done

exit $status
